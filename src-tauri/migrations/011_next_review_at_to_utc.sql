-- 011_next_review_at_to_utc.sql
-- 将 words.next_review_at 从"本地时间（无时区标记）"统一为 UTC 存储。
--
-- 背景：此前 fsrs.rs 以 chrono::Local::now() 写入本地时间字符串，到期比较依赖
-- datetime('now', 'localtime')。本地时间无时区信息，用户跨时区移动或夏令时切换后，
-- 存量数据与当前本地时区的对应关系断裂，due 判定会错位一个偏移量。
-- 改为 UTC 存储后，比较基准是 datetime('now')（恒为 UTC），与时区/DST 无关。
--
-- ============================================================================
-- 一次性换算假设（重要）：
-- 历史行只存了裸的本地时间字符串，无法可靠知道它当时属于哪个时区。
-- 这里采用**执行迁移那一刻服务器（本机）的当前本地时区偏移**做一次性换算：
-- SQLite 的 'utc' 修饰符按当前系统时区把输入视为本地时间并转换为 UTC。
-- 若用户在写入这些行之后更改过时区（或行落在与当前不同的 DST 区间内），
-- 换算结果会有偏差——这是无法避免的一次性近似。对复习调度的影响有限：
-- 最坏情况是个别词提前/推迟数小时进入待复习队列，且首次复习后会以 UTC 重新排程。
-- ============================================================================
-- 保守起见：格式非法（strftime 返回 NULL）的行保持原值不动，避免把坏数据抹成 NULL。
UPDATE words
SET next_review_at = strftime('%Y-%m-%d %H:%M:%S', next_review_at, 'utc')
WHERE next_review_at IS NOT NULL
  AND strftime('%Y-%m-%d %H:%M:%S', next_review_at, 'utc') IS NOT NULL;

-- 幂等保护：再次执行会把已转换的 UTC 时间再减一个偏移。
-- 版本化迁移本身只执行一次（_migrations 表跟踪），此注释仅为人工排查时提醒。
